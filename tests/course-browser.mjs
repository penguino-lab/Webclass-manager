import assert from 'node:assert/strict';
import { join } from 'node:path';
export async function checkCourse(context, site, artifacts) {
  const page = await context.newPage();
  try {
    await page.goto(site + 'course.php/26demo/');
    await page.locator('#wcl-course-filters').waitFor();
    const item = id => page.locator(`[data-contents-id="${id}"]`);
    assert.equal(await page.locator('#wcl-available-only').isChecked(), true);
    assert.equal(await page.locator('#wcl-period-only').isChecked(), false);
    assert.equal(await item('expired').isVisible(), false);
    assert.equal(await item('disabled').isVisible(), false);
    assert.equal(await item('unlimited').isVisible(), true);
    assert.equal(await page.locator('#folder-期限終了').isVisible(), false, 'empty folders hidden');
    assert.equal(await page.locator('.cm-sideNav_folders').isVisible(), false);
    assert.equal(await page.locator('.wcl-notification-banner').isVisible(), false);
    assert.equal(await page.locator('#unrelated-alert').isVisible(), true, 'unrelated alerts retained');
    assert.equal(await page.locator('.course-name').getAttribute('href'), null);
    await page.locator('.course-name').click();
    assert.equal(await page.evaluate(() => window.titleClicks || 0), 0);
    const home = await page.locator('.course-webclass').boundingBox(); assert.ok(home.height >= 44 && home.width >= 110);
    const homeStyle = await page.locator('.course-webclass').evaluate(el => { const style=getComputedStyle(el); return {background:style.backgroundColor,border:style.borderTopWidth,font:style.fontSize}; });
    assert.deepEqual(homeStyle,{background:'rgba(0, 0, 0, 0)',border:'0px',font:'18px'}, 'larger home text keeps a simple appearance');
    assert.equal(await page.locator('.course-webclass').textContent(), 'WebClass');
    assert.equal(await page.locator('.course-webclass .glyphicon-home').count(), 0);
    const homeText = await page.locator('.course-webclass').evaluate(el => { const range=document.createRange();range.selectNodeContents(el);const r=range.getBoundingClientRect();return {left:r.left,right:r.right}; });
    assert.ok(Math.abs(homeText.left-home.x-24)<1 && Math.abs(home.x+home.width-homeText.right-24)<1, 'home hit area extends equally on both sides of left-aligned text');
    await page.locator('.course-webclass').click({position:{x:12,y:22}});
    await page.locator('.course-webclass').click({position:{x:home.width-12,y:22}});
    assert.equal(await page.evaluate(() => window.homeClicks), 2, 'both side margins invoke the original home link');
    assert.equal(await page.locator('#wcl-course-filters').evaluate(el => getComputedStyle(el).borderRadius), '12px');
    assert.equal(await page.locator('#wcl-course-filters label').first().innerText(), '現在開ける教材だけ表示');
    assert.equal(await page.locator('#wcl-course-filters p:not(#wcl-filter-count)').count(), 0, 'no redundant search explanation');
    assert.equal(await page.locator('.wcl-course-bottom-home').evaluate(el => el.href), await page.locator('.course-webclass').evaluate(el => el.href));
    assert.equal(await page.locator('#native-top').count(), 0);
    const bottom = await page.locator('.wcl-course-bottom-home').boundingBox(); assert.ok(bottom.height >= 48);
    assert.equal(await page.locator('.wcl-course-bottom-home').evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(255, 255, 255)');
    assert.equal(await page.locator('#wcl-copy-code svg').getAttribute('fill'), 'none');
    assert.ok((await page.locator('#wcl-copy-code').boundingBox()).height <= 30, 'compact inline copy action');
    const materialStyle = await item('enabled').evaluate(el => ({padding:getComputedStyle(el).padding,minHeight:getComputedStyle(el).minHeight}));
    assert.equal(materialStyle.minHeight, '0px', 'no enlargement of material cards');
    const headerBeforeCopy = await page.locator('nav').boundingBox();
    const copyBefore = await page.locator('#wcl-copy-code').boundingBox();
    const copyTextBefore = await page.locator('#wcl-copy-code span').boundingBox();
    await context.grantPermissions(['clipboard-read', 'clipboard-write'], {origin:new URL(site).origin});
    await page.locator('#wcl-copy-code').click();
    assert.equal(await page.evaluate(() => navigator.clipboard.readText()), 'demo123');
    assert.equal(await page.locator('#wcl-copy-code span').textContent(), 'コピーしました✓');
    assert.equal(await page.locator('.wcl-copy-status').count(), 0, 'copy feedback stays in the original button');
    assert.deepEqual(await page.locator('#wcl-copy-code').boundingBox(), copyBefore, 'copy button stays the same size');
    assert.equal((await page.locator('#wcl-copy-code span').boundingBox()).x, copyTextBefore.x, 'copy text remains left-aligned after success');
    assert.deepEqual(await page.locator('nav').boundingBox(), headerBeforeCopy, 'copy feedback does not move header');
    await page.waitForFunction(() => document.querySelector('#wcl-copy-code span').textContent === '講義コードをコピー');
    assert.deepEqual(await page.locator('#wcl-copy-code').boundingBox(), copyBefore, 'restoring the label preserves size');
    await item('enabled').click({position:{x:12,y:12}});
    await page.locator('#folder-単独 .panel-heading').click();
    await item('enabled').focus(); await page.keyboard.press('Enter'); await page.keyboard.press('Space');
    await item('enabled').locator('.cm-contentsList_contentName a').click();
    assert.deepEqual(await page.evaluate(() => window.opened), Array(5).fill('enabled'), 'native opening action runs once');
    await item('enabled').locator('.detail').click();
    assert.equal(await page.evaluate(() => window.details), 1);
    assert.equal(await page.evaluate(() => window.opened.length), 5, 'detail is independent');
    await page.locator('#wcl-available-only').uncheck();
    assert.equal(await item('expired').isVisible(), true);
    assert.ok((await item('expired').getAttribute('class')).includes('wcl-unavailable'));
    const nameBox = await item('expired').locator('.cm-contentsList_contentName>div').boundingBox();
    const badgeBox = await item('expired').locator('.wcl-unavailable-badge').boundingBox();
    assert.ok(badgeBox.x >= nameBox.x + nameBox.width && Math.abs(badgeBox.y - nameBox.y) < 10, 'unavailable label is beside the name');
    await item('expired').click({position:{x:12,y:12}});
    assert.equal(await page.evaluate(() => window.opened.length), 5);
    await item('expired').locator('.detail').click(); assert.equal(await page.evaluate(() => window.details), 2);
    await page.locator('#wcl-period-only').check();
    assert.equal(await item('unlimited').isVisible(), false);
    assert.equal(await item('expired').isVisible(), true, 'period and availability differ');
    await page.locator('#wcl-available-only').check();
    assert.equal(await item('expired').isVisible(), false, 'filters intersect');
    await page.locator('#search-app input').fill('別の');
    await page.waitForFunction(() => document.querySelector('#wcl-filter-count').textContent.startsWith('1 件'));
    assert.equal(await item('enabled').isVisible(), false);
    assert.equal(await item('second').isVisible(), true);
    await page.locator('#search-app input').fill('存在しない');
    await page.waitForFunction(() => document.querySelector('#wcl-filter-count').textContent.includes('条件に合う教材はありません'));
    await page.locator('#search-app input').fill('');
    await page.waitForFunction(() => document.querySelector('#wcl-filter-count').textContent.startsWith('2 件'));
    await page.locator('#native-condition').click();
    await page.waitForFunction(() => document.querySelector('#wcl-filter-count').textContent.startsWith('1 件'));
    assert.equal(await item('enabled').isVisible(), false, 'native condition remains effective');
    await page.locator('#native-condition').click();
    await page.waitForFunction(() => document.querySelector('#wcl-filter-count').textContent.startsWith('2 件'));
    // Vue-style replacement must gain the current filters and click target.
    await page.evaluate(() => { const old=document.querySelector('[data-contents-id="second"]'); const next=old.cloneNode(true); next.querySelector('a').remove(); old.replaceWith(next); });
    await page.waitForFunction(() => document.querySelector('[data-contents-id="second"]').classList.contains('wcl-filtered-item'));
    await page.locator('#wcl-period-only').uncheck();
    await page.reload(); await page.locator('#wcl-course-filters').waitFor();
    assert.equal(await page.locator('#wcl-period-only').isChecked(), false);
    await page.screenshot({path:join(artifacts,'course-controls.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.locator('.course-webclass').isVisible(), true);
    assert.equal(await page.locator('#wcl-course-filters').isVisible(), true);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile layout fits');
    await page.screenshot({path:join(artifacts,'course-controls-mobile.png'),fullPage:true});
    await page.setViewportSize({width:1280,height:800});
    await page.goto(site + 'course.php/26demo/?staged=1');
    await page.waitForFunction(() => window.fixtureStage === 1);
    assert.equal(await page.locator('.cm-contentsList').isVisible(), false, 'first partial batch stays behind one loading boundary');
    assert.equal(await page.locator('#wcl-course-skeleton').isVisible(), true, 'skeleton replaces the hidden partial materials');
    assert.equal(await page.locator('.wcl-skeleton-card').count(), 3);
    const skeletonSearch = await page.locator('.wcl-skeleton-search').boundingBox();
    await page.screenshot({path:join(artifacts,'course-loading-skeleton.png'),fullPage:true});
    await page.emulateMedia({reducedMotion:'reduce'});
    assert.equal(await page.locator('.wcl-skeleton-visual').evaluate(el => getComputedStyle(el).animationName), 'none');
    await page.emulateMedia({reducedMotion:'no-preference'});
    await page.waitForFunction(() => window.fixtureStage === 3);
    assert.equal(await page.locator('.cm-contentsList').isVisible(), false, 'later partial batch stays hidden');
    await page.locator('#wcl-course-filters').waitFor();
    assert.equal(await page.evaluate(() => window.fixtureStage), 4);
    assert.equal(await page.locator('.wcl-course-card').count(), 5);
    assert.equal(await page.locator('[data-wcl-course-loading]').count(), 0);
    assert.equal(await page.locator('#wcl-course-skeleton').count(), 0, 'skeleton is removed together with the loading boundary');
    const searchAfterLoading = await page.locator('#search-app').boundingBox();
    assert.ok(Math.abs(skeletonSearch.y-searchAfterLoading.y)<1, 'skeleton and native search start at the same vertical position');
    assert.equal(await page.locator('nav').evaluate(el => el.getBoundingClientRect().height), await page.evaluate(() => window.initialHeaderHeight), 'reserved copy slot prevents header shift');
    // Empty/error-like responses must never stay hidden indefinitely.
    await page.goto(site + 'course.php/26demo/?empty=1');
    await page.locator('#wcl-course-filters').waitFor();
    assert.match(await page.locator('#wcl-filter-count').textContent(), /条件に合う教材はありません/);
    assert.equal(await page.locator('[data-wcl-course-loading]').count(), 0);
    assert.equal(await page.locator('#wcl-course-skeleton').count(), 0, 'empty-page fallback also removes the skeleton');
    console.log('PASS: compact copy and outline icon; native material dimensions; inline unavailable label; white home; staged initial loading and bounded empty-page fallback; stable header feedback; course filters/native search');
  } finally { await page.close(); }
}
